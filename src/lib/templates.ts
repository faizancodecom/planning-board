export function createPlanFromTemplate(templateId: string, customTitle?: string): PlnFileContent {
  const template = TEMPLATES.find((t) => t.id === templateId) || TEMPLATES[0];
  const title = customTitle || `${template.title}`;
  
  return createNewPlnContent(
    title,
    {
      description: template.description,
      tags: template.tags,
      category: template.category,
      boardType: template.boardType || (template.category === 'flowchart' ? 'flowchart' : 'planning'),
    },
    // Clone elements with new unique IDs to avoid conflicts
    template.elements.map((el) => ({
      ...el,
      id: `elem_${Date.now().toString(36)}_${Math.random().toString(36).substring(2, 6)}`,
    }))
  );
}
